CREATE TABLE lietotajs (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(100) NOT NULL UNIQUE,
    nick                VARCHAR(50) NOT NULL UNIQUE,
    kontakt_informacija VARCHAR(200),
    password_hash       VARCHAR(255) NOT NULL,
    ir_banots            BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX idx_lietotajs_email_lower ON lietotajs (lower(email));
CREATE UNIQUE INDEX idx_lietotajs_nick_lower ON lietotajs (lower(nick));

CREATE TABLE admin (
    id    INTEGER PRIMARY KEY REFERENCES lietotajs(id) ON DELETE CASCADE,
    vards VARCHAR(50) NOT NULL
);

CREATE TYPE ban_status AS ENUM ('ir', 'nav');

CREATE TABLE lietotaja_bans (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pamatojums   TEXT NOT NULL,
    datums       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    beigu_datums TIMESTAMP,
    ir_aktivs    ban_status NOT NULL,
    lietotajs_id INTEGER NOT NULL REFERENCES lietotajs(id),
    admin_id     INTEGER NOT NULL REFERENCES admin(id)
);

CREATE TABLE spele (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nosaukums VARCHAR(100) NOT NULL UNIQUE,
    attels    VARCHAR(500),
    admin_id  INTEGER NOT NULL REFERENCES admin(id)
);

CREATE TABLE anketa (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apraksts     VARCHAR(600) NOT NULL,
    ir_dzesta    BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lietotajs_id INTEGER NOT NULL REFERENCES lietotajs(id),
    spele_id     INTEGER NOT NULL REFERENCES spele(id),
    UNIQUE (lietotajs_id, spele_id)
);

CREATE TYPE reakcijas_tips AS ENUM ('patik', 'nepatik');

CREATE TABLE reakcija (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tips         reakcijas_tips NOT NULL,
    datums       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lietotajs_id INTEGER NOT NULL REFERENCES lietotajs(id),
    anketa_id    INTEGER NOT NULL REFERENCES anketa(id),
    UNIQUE (lietotajs_id, anketa_id)
);

CREATE TABLE zinojums (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pamatojums   VARCHAR(1000) NOT NULL,
    datums       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    anketa_id    INTEGER NOT NULL REFERENCES anketa(id),
    lietotajs_id INTEGER NOT NULL REFERENCES lietotajs(id),
    admin_id     INTEGER REFERENCES admin(id),
    UNIQUE (lietotajs_id, anketa_id)
);

CREATE TYPE speles_lauka_tips AS ENUM ('teksts', 'skaitlis', 'izvele', 'atzimes_rukis');

CREATE TABLE speles_lauks (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spele_id    INTEGER NOT NULL REFERENCES spele(id),
    nosaukums   VARCHAR(50) NOT NULL,
    lauka_tips  speles_lauka_tips NOT NULL,
    ir_obligats BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (spele_id, nosaukums)
);

CREATE TABLE speles_lauka_variants (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    speles_lauks_id INTEGER NOT NULL REFERENCES speles_lauks(id) ON DELETE CASCADE,
    vertiba         VARCHAR(100) NOT NULL,
    UNIQUE (speles_lauks_id, vertiba)
);

CREATE TABLE anketas_lauka_vertiba (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anketa_id       INTEGER NOT NULL REFERENCES anketa(id) ON DELETE CASCADE,
    speles_lauks_id INTEGER NOT NULL REFERENCES speles_lauks(id) ON DELETE CASCADE,
    vertiba         VARCHAR(200) NOT NULL,
    UNIQUE (anketa_id, speles_lauks_id)
);

CREATE INDEX idx_anketa_spele_active ON anketa(spele_id, ir_dzesta);
CREATE INDEX idx_reakcija_user ON reakcija(lietotajs_id);
CREATE INDEX idx_zinojums_pending ON zinojums(admin_id) WHERE admin_id IS NULL;
CREATE INDEX idx_bans_user_active ON lietotaja_bans(lietotajs_id, ir_aktivs);